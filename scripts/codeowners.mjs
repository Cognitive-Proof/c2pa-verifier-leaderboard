// Writes .github/CODEOWNERS from owners.json, so each company is asked to review changes to its
// own results file and maintainers own everything else. Run it after editing owners.json.
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { readJson } from "./lib.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const owners = readJson(join(root, "owners.json"));
const at = (list) => list.map((l) => `@${l}`).join(" ");
const maintainers = at(owners.maintainers);

const lines = [
  "# Generated by scripts/codeowners.mjs from owners.json. Do not edit by hand.",
  "",
  `*                          ${maintainers}`,
  "",
  "# Each company owns its results file.",
  ...Object.entries(owners.companies).map(
    ([id, c]) => `/results/${id}.json`.padEnd(27) + ` ${at([...new Set([...c.github, ...owners.maintainers])])}`,
  ),
  "",
  "# Only maintainers decide who owns what.",
  `/owners.json                ${maintainers}`,
  `/.github/                   ${maintainers}`,
  `/scripts/                   ${maintainers}`,
  "",
];
writeFileSync(join(root, ".github", "CODEOWNERS"), lines.join("\n"));
console.log("Wrote .github/CODEOWNERS");
